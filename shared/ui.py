# -- text direction -------------------------------------------------------
def has_arabic(text: str | None) -> bool:
    return bool(text and _ARABIC_RE.search(text))


def text_direction(text: str | None) -> str:
    """'rtl' when the text contains Arabic letters, else 'ltr'."""
    return "rtl" if has_arabic(text) else "ltr"


def bidi_html(text: str | None) -> str:
    """Escaped HTML span whose direction follows its content (Arabic shows right-to-left)."""
    value = html.escape(text or "")
    if has_arabic(text):
        return f'<span class="wrl-rtl" dir="rtl">{value}</span>'
    return f'<span class="wrl-auto" dir="auto">{value}</span>'


def show_text(text: str | None, label: str | None = None) -> None:
    """Show free text (a call note, a field note) with the right direction."""
    prefix = f"<strong>{html.escape(label)}:</strong><br>" if label else ""
    tag = "div"
    direction = text_direction(text)
    css = "wrl-rtl" if direction == "rtl" else "wrl-auto"
    st.markdown(f'{prefix}<{tag} class="{css}" dir="{direction}">{html.escape(text or "")}</{tag}>', unsafe_allow_html=True)


# -- page frame -----------------------------------------------------------
def inject_css() -> None:
    st.markdown(CSS, unsafe_allow_html=True)


def demo_banner() -> None:
    st.markdown(f'<div class="wrl-banner" role="note"><strong>DEMO</strong> · {html.escape(DEMO_BANNER[6:])}</div>', unsafe_allow_html=True)


# Pages that only read (classifier lab, needs map, live board, sitrep search) stay
# open in server mode, so the operations room board runs with nobody logged in.
READ_ONLY_PROJECTS = frozenset({3, 9, 17, 19})


def page_header(
    title: str | None = None,
    project_number: int | None = None,
    subtitle: str | None = None,
    layout: str = "wide",
    icon: str = "🧭",
) -> None:
    """Page config, styles, demo banner and title. Call it first in every app.

    With project_number the title and the "who / what" line come from that
    project's project.toml.
    """
    who = None
    if project_number is not None:
        from shared.projects import get_project

        project = get_project(project_number)
        title = title or f"{project.code} · {project.title}"
        who = f"Used by: {project.user}. Task: {project.task}"
    title = title or BRAND
    st.set_page_config(page_title=f"{title} | {BRAND}", page_icon=icon, layout=layout)  # type: ignore[arg-type]
    inject_css()
    demo_banner()
    st.markdown(f'<div class="wrl-brand">{html.escape(BRAND)}</div>', unsafe_allow_html=True)
    st.title(title)
    if subtitle or who:
        st.markdown(f'<div class="wrl-who">{html.escape(subtitle or who or "")}</div>', unsafe_allow_html=True)
    if project_number is not None:
        st.sidebar.markdown(f"[← Portfolio homepage]({ports.homepage_url()})")
    if project_number not in READ_ONLY_PROJECTS:
        # Server mode: every page that can change data stops here until a staff login
        # succeeds. Local demo mode: this does nothing.
        from shared import auth

        auth.require_staff_login()


def section(title: str, caption: str | None = None) -> None:
    st.subheader(title)
    if caption:
        st.caption(caption)


def metric_row(metrics: Sequence[tuple[str, Any] | tuple[str, Any, str]]) -> None:
    """A row of st.metric tiles. Each item is (label, value) or (label, value, help). Put units in labels."""
    cols = st.columns(len(metrics))
    for col, m in zip(cols, metrics, strict=True):
        col.metric(m[0], m[1], help=m[2] if len(m) > 2 else None)  # type: ignore[misc]


def table(df: pd.DataFrame, height: int | str = "auto", column_config: dict[str, Any] | None = None, key: str | None = None) -> None:
    st.dataframe(df, width="stretch", height=height, hide_index=True, column_config=column_config, key=key)  # type: ignore[arg-type]


def badge(text: str, kind: str = "ok") -> str:
    """HTML badge. kind: ok, warn, bad, stale. Use with st.markdown(..., unsafe_allow_html=True)."""
    css = {"ok": "wrl-ok", "warn": "wrl-warn", "bad": "wrl-bad", "stale": "wrl-stale"}.get(kind, "wrl-ok")
    return f'<span class="wrl-badge {css}">{html.escape(text)}</span>'


def minutes_since(timestamp: str | datetime | None, now: datetime | None = None) -> float | None:
    if timestamp is None:
        return None
    ts = timestamp if isinstance(timestamp, datetime) else clock.parse(str(timestamp))
    return round(((now or clock.now()) - ts).total_seconds() / 60.0, 1)


def freshness_badge(timestamp: str | datetime | None, stale_after_minutes: float, now: datetime | None = None) -> str:
    """'Updated N min ago' badge that turns into a visible STALE badge past the limit."""
    if timestamp is None:
        return badge("STALE: no data", "stale")
    ts = timestamp if isinstance(timestamp, datetime) else clock.parse(str(timestamp))
    # Unrounded, so the badge and shared.fleet.is_stale agree just past the limit.
    age = ((now or clock.now()) - ts).total_seconds() / 60.0
    label = f"{int(age)} min ago" if age < 120 else f"{age / 60:.1f} h ago"
    if age > stale_after_minutes:
        return badge(f"STALE: last update {label}", "stale")
    return badge(f"Updated {label}", "ok")


# -- staff ----------------------------------------------------------------
def staff_options(roles: Sequence[str] | None = None) -> list[dict[str, Any]]:
    sql = "SELECT staff_id, display_name, role FROM staff WHERE active = 1"
    params: list[str] = []
    if roles:
        sql += f" AND role IN ({','.join('?' for _ in roles)})"
        params = list(roles)
    return db.query_all(sql + " ORDER BY staff_id", params)


def staff_selector(roles: Sequence[str] | None = None, key: str = "acting_staff", label: str = "Acting as") -> str | None:
    """Sidebar role selector (local demo mode has no accounts). Returns the chosen staff_id."""
    options = staff_options(roles)
    if not options:
        st.sidebar.warning("No staff with the required role in the database.")
        return None
    labels = {o["staff_id"]: f"{o['staff_id']} · {o['display_name']} ({o['role'].replace('_', ' ')})" for o in options}
    return st.sidebar.selectbox(label, list(labels), format_func=lambda s: labels[s], key=key)


def confirm_action(
    key: str,
    summary: str,
    roles: Sequence[str] | None = None,
    button_label: str = "Confirm",
    default_staff: str | None = None,
) -> str | None:
    """Staff confirmation step for a consequential action.

    Shows what will happen, asks which staff member confirms, and requires a
    tick box before the button counts. Returns the confirming staff_id on the run
    where it was confirmed, otherwise None. Pair it with
    shared.confirm.require_confirmation inside the domain function.
    """
    options = staff_options(roles)
    ids = [o["staff_id"] for o in options]
    with st.form(key=f"confirm_{key}", border=True):
        st.markdown("**Staff confirmation required**")
        st.markdown(summary)
        index = ids.index(default_staff) if default_staff in ids else 0
        staff_id = st.selectbox("Confirming staff member", ids, index=index if ids else None, key=f"confirm_staff_{key}")
        ticked = st.checkbox("I have reviewed the details above and confirm this action.", key=f"confirm_tick_{key}")
        submitted = st.form_submit_button(button_label, type="primary")
    if not submitted:
        return None
    if not ticked:
        st.warning("Tick the confirmation box first. Nothing was changed.")
        return None
    if not staff_id:
        st.warning("Choose the confirming staff member. Nothing was changed.")
        return None
    return str(staff_id)
